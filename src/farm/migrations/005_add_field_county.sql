-- 迁移 v5 —— 田块补「县/区」（任务清单 7.1 的一个补口）
--
-- 为什么加这一列：
--   v2 建表时 fields 只到「市」一级，新建田块靠手填经纬度。可农户报位置是报到县的
--   （「湖北省 武汉市 洪山区」），不会报经纬度；而天气、积温、3D 全都挂在坐标上。
--   于是这一列不是装饰：前端按「省/市/县」三级联动选址，再由三级中心点**取平均**
--   推出经纬度（算法在 frontend/assets/js/farm.js），县是其中一级。
--
-- 为什么 NOT NULL DEFAULT ''：
--   旧库里已有的田块没有县可填，给 '' 比给 NULL 好 —— 读的时候不用在
--   「没有这一级」和「还没填」之间猜；这也是 province / city 两列本来的做法。
--
-- 为什么不加索引：
--   没有任何查询按 county 过滤。它只在整行读出来之后给前端显示。

ALTER TABLE fields ADD COLUMN county TEXT NOT NULL DEFAULT '';
